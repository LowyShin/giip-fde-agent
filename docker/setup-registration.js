#!/usr/bin/env node
// Materializes csn-projects.json + giip-accounts.json from env vars so a fresh
// container can register a CSN/project without manual file editing.
// See docs/60-operations/hourly-issue-scheduler.md §13 (formerly §8) and
// slack-bot/README.md "Per-project giip CSN routing" for the manual procedure
// this automates. Existing files are left untouched unless GIIP_FORCE_REGEN=true
// (idempotent — safe to re-run on every container start).

const fs = require('fs');
const path = require('path');

const REPO_DIR = process.env.REPO_DIR || '/work/giip-fde-agent';
const forceRegen = process.env.GIIP_FORCE_REGEN === 'true';

function writeIfAbsent(filePath, buildContent, label) {
  if (fs.existsSync(filePath) && !forceRegen) {
    console.log(`[setup-registration] ${label}: already exists, skip (${filePath})`);
    return;
  }
  const content = buildContent();
  if (content === null) {
    console.log(`[setup-registration] ${label}: required env vars missing, skip`);
    return;
  }
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, 'utf8');
  console.log(`[setup-registration] ${label}: wrote ${filePath}`);
}

// ── scripts/gissue/csn-projects.json (scheduler CSN -> workdir mapping) ──
writeIfAbsent(
  path.join(REPO_DIR, 'scripts/gissue/csn-projects.json'),
  () => {
    const csn = process.env.GIIP_CSN;
    if (!csn) return null;
    const entry = {
      project: process.env.GIIP_PROJECT_NAME || 'docker',
      workdir: process.env.GIIP_WORKDIR || REPO_DIR,
      enabled: true,
      note: 'auto-generated by docker/setup-registration.js',
    };
    if (process.env.GIIP_REST_BRANCH) entry.restBranch = process.env.GIIP_REST_BRANCH;
    const doc = {
      forcedUnblockExcludeRepoNames: [],
      guardRepos: [],
      csn: { [csn]: entry },
    };
    return JSON.stringify(doc, null, 2) + '\n';
  },
  'csn-projects.json'
);

// ── slack-bot/.secrets/giip-accounts.json (csn/sk/login_id mapping) ──
writeIfAbsent(
  path.join(REPO_DIR, 'slack-bot/.secrets/giip-accounts.json'),
  () => {
    const loginId = process.env.GIIP_LOGIN_ID;
    const sk = process.env.GIIP_SK;
    const csn = process.env.GIIP_CSN;
    if (!loginId || !sk || !csn) return null;
    const account = { login_id: loginId, sk, csn: Number(csn) };
    const doc = {
      GIIP_API_BASE: process.env.GIIP_API_BASE || 'https://giipfaw.azurewebsites.net/api',
      default: account,
      channels: {},
    };
    if (process.env.SLACK_CHANNEL_ID) {
      doc.channels[process.env.SLACK_CHANNEL_ID] = account;
    }
    return JSON.stringify(doc, null, 2) + '\n';
  },
  'giip-accounts.json'
);
